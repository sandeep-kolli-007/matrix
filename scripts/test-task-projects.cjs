const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('typescript');
const path = require('node:path');
const moduleExports = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync(path.join(__dirname, '../src/data/task-projects.ts'), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { exports: moduleExports });
const { taskProjectOptions, selectTaskProject } = moduleExports;
const record = (id, type, extra = {}) => ({ id, title: 'Same title', kind: type.toLowerCase(), metadata: { entityType: type }, ...extra });
const trip = record('trip', 'Trip');
const project = record('project', 'Project');
const all = [trip, project, record('plan', 'Plan'), record('goal', 'Goal'), record('old', 'Trip', { archivedAt: '2026-01-01' }), record('task', 'Task'), record('meal', 'Meal')];
assert.equal(taskProjectOptions(all).length, 4);
assert.equal(taskProjectOptions(all, 'trip').length, 3);
let next = selectTaskProject({ priority: 'High' }, ['person'], trip);
assert.equal(next.values.projectId, 'trip');
assert.equal(next.values.priority, 'High');
assert.equal(next.relatedIds.join(','), 'person,trip');
next = selectTaskProject(next.values, next.relatedIds, project);
assert.equal(next.values.projectId, 'project');
assert.equal(next.relatedIds.join(','), 'person,project');
next = selectTaskProject(next.values, next.relatedIds);
assert.equal(next.values.projectId, '');
assert.equal(next.values.project, '');
assert.equal(next.relatedIds.join(','), 'person');
assert.equal(selectTaskProject({ project: 'Legacy text' }, [], undefined).values.project, '');
const habitLink = selectTaskProject({ frequency: 'Weekdays', goalId: 'old-goal', goal: 'Old goal' }, ['old-goal', 'person'], project, 'goal');
assert.equal(habitLink.values.goalId, 'project');
assert.equal(habitLink.values.goal, project.title);
assert.equal(habitLink.values.frequency, 'Weekdays');
assert.equal(habitLink.relatedIds.join(','), 'person,project');
assert.equal(selectTaskProject(habitLink.values, habitLink.relatedIds, undefined, 'goal').relatedIds.join(','), 'person');
console.log('PASS: eligible saved entities, archived/self exclusions, duplicate titles, stable IDs, replace/clear and unrelated links.');
